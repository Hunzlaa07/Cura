// Get the saved language from localStorage, or detect from browser
const getSavedLanguage = () => {
  const saved = localStorage.getItem('preferredLanguage');
  if (saved) {
    return saved;
  }
  // Fallback to browser language detection
  const browserLang = navigator.language.split('-')[0];
  return browserLang === 'ar' ? 'ar' : 'en';
};

const initialLanguage = getSavedLanguage();

i18n
  .use(LanguageDetector) // Detects user language
  .use(initReactI18next) // Passes i18n to react-i18next
  .init({
    resources,
    fallbackLng: 'en', // Default language
    lng: initialLanguage, // ✅ Use saved language or detected language
    interpolation: {
      escapeValue: false // React already escapes values
    },
    detection: {
      order: ['localStorage', 'navigator'],
      caches: ['localStorage'],
      lookupLocalStorage: 'preferredLanguage' // ✅ Specify the localStorage key
    }
  });

// ✅ IMPORTANT: Save language preference whenever it changes
i18n.on('languageChanged', (lng) => {
  localStorage.setItem('preferredLanguage', lng);
  document.documentElement.dir = lng === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lng;
});

export default i18n;